def _age_bucket(age_str: str) -> str:
    try:
        age = int(age_str.strip())
    except (ValueError, TypeError, AttributeError):
        return "Unknown"
    if age == 2:
        return "2yo"
    if age == 3:
        return "3yo"
    if age == 4:
        return "4yo"
    if age == 5:
        return "5yo"
    if age == 6:
        return "6yo"
    return "7yo+"


def _class_bucket(race_class) -> str:
    if race_class is None:
        return "Unknown"
    s = str(race_class).strip().lower()
    if s.startswith("class"):
        s = s[5:].strip()
    if "grade 1" in s or "listed" in s:
        return "Elite"
    if "grade" in s:
        return "Graded"
    try:
        c = int(s)
        if c <= 2:
            return "Class1-2"
        if c <= 4:
            return "Class3-4"
        return "Class5+"
    except (TypeError, ValueError):
        return "Unknown"


def analyse_age(all_races: list[dict], result_lookup: dict) -> dict:
    by_age: dict[str, WinStats] = defaultdict(WinStats)
    # age_bucket × class_bucket
    by_age_class: dict[str, dict[str, WinStats]] = defaultdict(lambda: defaultdict(WinStats))
    # variance: track positions to compute std dev
    age_positions: dict[str, list[int]] = defaultdict(list)

    for race in all_races:
        race_class = race.get("class")
        cls_bkt = _class_bucket(race_class)
        for runner in (race.get("runners") or []):
            age_bkt = _age_bucket(_safe_str(runner.get("age")))
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            won = pos_int == 1
            placed = pos_int <= 3
            by_age[age_bkt].record(won, placed, sp)
            by_age_class[age_bkt][cls_bkt].record(won, placed, sp)
            if pos_int < 20:
                age_positions[age_bkt].append(pos_int)

    # Variance proxy: std dev of finishing positions
    age_variance: dict[str, float] = {}
    for bkt, positions in age_positions.items():
        if len(positions) >= 5:
            mean = sum(positions) / len(positions)
            variance = sum((p - mean) ** 2 for p in positions) / len(positions)
            age_variance[bkt] = round(variance ** 0.5, 2)

    age_summary: dict[str, dict] = {}
    for bkt in ("2yo", "3yo", "4yo", "5yo", "6yo", "7yo+", "Unknown"):
        if bkt in by_age and by_age[bkt].runs > 0:
            d = by_age[bkt].to_dict()
            d["position_std_dev"] = age_variance.get(bkt)
            age_summary[bkt] = d

    # Cross-tab: age × class
    age_class_table: dict[str, dict] = {}
    for age_bkt, class_dict in by_age_class.items():
        age_class_table[age_bkt] = {
            cls: stats.to_dict()
            for cls, stats in class_dict.items()
            if stats.runs >= 5
        }

    return {
        "by_age": age_summary,
        "age_position_variance": age_variance,
        "age_class_crosstab": age_class_table,
    }


