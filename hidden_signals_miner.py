# SIGNAL 9: QUICK RETURN — FLAT vs JUMPS SPLIT
# ---------------------------------------------------------------------------

def analyse_quick_return(all_races: list[dict], result_lookup: dict) -> dict:
    """
    last_run days → win rate for flat vs jump races.
    Current model: applies same freshness bonus regardless of race type.
    Hypothesis: quick return (<7 days) helps flat horses but not jump horses.
    """
    # type_tag -> days_bucket -> WinStats
    by_type_return: dict[str, dict[str, WinStats]] = {
        "flat": defaultdict(WinStats),
        "jump": defaultdict(WinStats),
    }

    def _days_bucket(days: int) -> str:
        if days < 0:
            return "unknown"
        if days < 7:
            return "<7_days"
        if days < 14:
            return "7-13_days"
        if days < 28:
            return "14-27_days"
        if days < 45:
            return "28-44_days"
        if days < 70:
            return "45-69_days"
        return "70+_days"

    for race in all_races:
        type_tag = "flat" if _is_flat(race) else "jump"
        for runner in (race.get("runners") or []):
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            last_run = _safe_int(runner.get("last_run"), default=-1)
            days_bkt = _days_bucket(last_run)
            won = pos_int == 1
            placed = pos_int <= 3
            by_type_return[type_tag][days_bkt].record(won, placed, sp)

    result: dict[str, dict] = {}
    for type_tag, bucket_dict in by_type_return.items():
        result[type_tag] = {
            bkt: stats.to_dict()
            for bkt, stats in bucket_dict.items()
            if stats.runs >= 5
        }

    # Key comparison: quick return (<7 days) flat vs jump
    flat_quick = by_type_return["flat"]["<7_days"]
    jump_quick = by_type_return["jump"]["<7_days"]
    flat_norm = by_type_return["flat"]["14-27_days"]   # baseline
    jump_norm = by_type_return["jump"]["14-27_days"]   # baseline

    comparison: dict = {}
    if flat_quick.runs >= 5:
        comparison["flat_quick_return_win_pct"] = round(flat_quick.win_pct, 1)
    if jump_quick.runs >= 5:
        comparison["jump_quick_return_win_pct"] = round(jump_quick.win_pct, 1)
    if flat_norm.runs >= 5:
        comparison["flat_normal_break_win_pct"] = round(flat_norm.win_pct, 1)
    if jump_norm.runs >= 5:
        comparison["jump_normal_break_win_pct"] = round(jump_norm.win_pct, 1)

    # Assessment
    assessment = "insufficient data"
    fq = comparison.get("flat_quick_return_win_pct")
    jq = comparison.get("jump_quick_return_win_pct")
    fn = comparison.get("flat_normal_break_win_pct")
    jn = comparison.get("jump_normal_break_win_pct")
    if fq is not None and jq is not None and fn is not None:
        if fq >= fn and jq < jn:
            assessment = f"CONFIRMED: flat quick return outperforms baseline ({fq}% vs {fn}%), jump quick return underperforms ({jq}% vs {jn}%)"
        elif fq >= fn and jq >= jn:
            assessment = f"PARTIALLY CONFIRMED: both flat and jump quick return OK, but flat gains more ({fq}% flat, {jq}% jump)"
        elif fq < fn:
            assessment = f"NOT CONFIRMED: flat quick return ({fq}%) below flat baseline ({fn}%)"
        else:
            assessment = f"AMBIGUOUS: flat={fq}% baseline={fn}%, jump={jq}% baseline={jn}%"

    return {
        "by_race_type_and_days_since_last_run": result,
        "quick_return_comparison": comparison,
        "assessment": assessment,
    }


