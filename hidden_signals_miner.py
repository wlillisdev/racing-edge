    sn_pct = sn_stats.get("win_pct", 0)
    baseline_sent = commentary_r.get("baseline_neutral_win_pct")
    high_alpha = commentary_r.get("high_alpha_keywords") or []

    if coverage >= 20 and baseline_sent is not None:
        delta_sp = round(sp_pct - baseline_sent, 1) if sp_stats.get("runs", 0) >= 10 else None
        delta_sn = round(sn_pct - baseline_sent, 1) if sn_stats.get("runs", 0) >= 10 else None
        if delta_sp is not None and delta_sp >= 5.0:
            sig = "MEDIUM"
            note = f"Strong positive commentary: {sp_pct}% win rate (+{delta_sp}% over neutral). Alpha present."
        elif delta_sp is not None:
            sig = "LOW"
            note = f"Positive commentary: {sp_pct}% win rate ({delta_sp:+}% vs neutral). Marginal."
        else:
            sig = "PENDING_DATA"
            note = f"Commentary coverage {coverage}% but few strong-positive cases."
        top_kw = [k["keyword"] for k in high_alpha[:5]] if high_alpha else []
        recs.append({
            "rank": None, "signal": "Commentary / Spotlight NLP",
            "significance": sig,
            "evidence": f"Coverage: {coverage}%. {note}. Top alpha keywords: {top_kw}.",
            "recommendation": (
                "Add commentary_score component (max +3pts). "
                "Trigger: spotlight/quotes contains strong_positive keywords. "
                "Stable-tour quotes ('should win', 'very well') are highest alpha."
            ),
            "estimated_impact": "LOW-MEDIUM — commentary is already partially modelled (+2pts for 'stable commentary present') but keyword sentiment is not.",
        })
    else:
        recs.append({
            "rank": None, "signal": "Commentary / Spotlight NLP",
            "significance": "PENDING_DATA",
            "evidence": f"Commentary coverage: {coverage}% (need 20%+ to be useful).",
            "recommendation": "Commentary fields may not be populated in backtest cache. Run with live data.",
            "estimated_impact": "Expected LOW-MEDIUM.",
        })

    # --- Age ---
    age_by = age_r.get("by_age") or {}
    if len(age_by) >= 3:
        # Find highest win % age group vs average
        age_win_rates = {k: v.get("win_pct", 0) for k, v in age_by.items() if v.get("runs", 0) >= 20}
        if age_win_rates:
            best_age = max(age_win_rates, key=lambda x: age_win_rates[x])
            worst_age = min(age_win_rates, key=lambda x: age_win_rates[x])
            spread = age_win_rates[best_age] - age_win_rates[worst_age]
            sig = "MEDIUM" if spread >= 5.0 else "LOW"
            recs.append({
                "rank": None, "signal": "Age Patterns",
                "significance": sig,
                "evidence": f"Best: {best_age} ({age_win_rates[best_age]:.1f}% win). Worst: {worst_age} ({age_win_rates[worst_age]:.1f}% win). Spread: {spread:.1f}%.",
                "recommendation": (
                    f"Consider age penalty for {worst_age} horses in competitive races. "
                    "2yo and 3yo debutants have higher variance — flagging in Shadow list."
                ),
                "estimated_impact": "LOW — age interacts with class level, complex to model cleanly.",
            })

    # --- Sex patterns ---
    sex_by = sex_r.get("by_sex") or {}
    if len(sex_by) >= 2:
        sex_win_rates = {k: v.get("win_pct", 0) for k, v in sex_by.items() if v.get("runs", 0) >= 20}
        if len(sex_win_rates) >= 2:
            best_sex = max(sex_win_rates, key=lambda x: sex_win_rates[x])
            worst_sex = min(sex_win_rates, key=lambda x: sex_win_rates[x])
            sex_spread = sex_win_rates[best_sex] - sex_win_rates[worst_sex]
            sex_var = sex_r.get("sex_position_variance") or {}
            gelding_var = sex_var.get("Gelding")
            filly_var = sex_var.get("Filly")
            var_note = ""
            if gelding_var and filly_var:
                var_note = f" Gelding position std dev: {gelding_var}, Filly: {filly_var}."
            recs.append({
                "rank": None, "signal": "Sex / Gender Patterns",
                "significance": "MEDIUM" if sex_spread >= 4.0 else "LOW",
                "evidence": f"Best: {best_sex} ({sex_win_rates[best_sex]:.1f}% win). Worst: {worst_sex} ({sex_win_rates[worst_sex]:.1f}% win). Spread: {sex_spread:.1f}%.{var_note}",
                "recommendation": (
                    "Geldings are more consistent (lower variance) — "
                    "consider +1pt for geldings in handicaps. Fillies/mares have higher variance — "
                    "consider flagging with uncertainty note."
                ),
                "estimated_impact": "LOW — marginal signal, not worth major model change alone.",
            })

    # --- Weight ---
    wt_sweet = weight_r.get("sweet_spot_bracket")
    wt_pct = weight_r.get("sweet_spot_win_pct")
    wt_by = weight_r.get("by_weight_bracket") or {}
    if wt_sweet and wt_pct and len(wt_by) >= 3:
        # Compare topweight to sweet spot
        heavy_stats = wt_by.get("9-7 to 9-13") or wt_by.get("10-0+ (topweight)") or {}
        heavy_pct = heavy_stats.get("win_pct", 0)
        penalty_evidence = f"Sweet spot: {wt_sweet} ({wt_pct}% win). Heavy weight (9-7+): {heavy_pct}%."
        spread_wt = wt_pct - heavy_pct
        recs.append({
            "rank": None, "signal": "Weight Carried",
            "significance": "MEDIUM" if spread_wt >= 4.0 else "LOW",
            "evidence": penalty_evidence,
            "recommendation": (
                "Weight is already implicitly captured via OR (official rating). "
                "However, top weight in handicaps (9-7+) deserves explicit -2pt penalty "
                "if win rate is materially below average."
            ),
            "estimated_impact": "LOW — weight correlates with class/OR which is already scored.",
        })

    # --- Rank by significance ---
    significance_order = {"HIGH": 0, "MEDIUM": 1, "LOW": 2, "PENDING_DATA": 3}
    recs.sort(key=lambda r: significance_order.get(r.get("significance", "PENDING_DATA"), 3))
    for i, r in enumerate(recs, 1):
        r["rank"] = i

    return recs


