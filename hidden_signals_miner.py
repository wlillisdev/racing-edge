def _weight_bucket(lbs: int) -> str:
    """
    Typical racing weights:
      126 lbs = 9-0  (9 stone)
      133 lbs = 9-7
      126 = 9-0, 119 = 8-7, 112 = 8-0 (rarely seen)
    Common spread: 118–135 lbs
    """
    if lbs <= 0:
        return "Unknown"
    if lbs < 119:
        return "<8-7 (featherweight)"
    if lbs < 126:
        return "8-7 to 8-13"
    if lbs < 133:
        return "9-0 to 9-6"
    if lbs < 140:
        return "9-7 to 9-13"
    return "10-0+ (topweight)"


def analyse_weight(all_races: list[dict], result_lookup: dict) -> dict:
    by_weight: dict[str, WinStats] = defaultdict(WinStats)
    # flat vs jump split
    by_weight_type: dict[str, dict[str, WinStats]] = defaultdict(lambda: defaultdict(WinStats))

    for race in all_races:
        race_type_tag = "flat" if _is_flat(race) else "jump"
        for runner in (race.get("runners") or []):
            # Prefer weight_lbs; fall back to lbs
            lbs = _safe_int(runner.get("weight_lbs"), default=-1)
            if lbs <= 0:
                lbs = _safe_int(runner.get("lbs"), default=-1)
            wt_bkt = _weight_bucket(lbs)
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            won = pos_int == 1
            placed = pos_int <= 3
            by_weight[wt_bkt].record(won, placed, sp)
            by_weight_type[wt_bkt][race_type_tag].record(won, placed, sp)

    weight_summary: dict[str, dict] = {
        bkt: stats.to_dict()
        for bkt, stats in by_weight.items()
        if stats.runs >= 5
    }
    weight_by_type: dict[str, dict] = {
        bkt: {
            t: s.to_dict() for t, s in type_dict.items() if s.runs >= 5
        }
        for bkt, type_dict in by_weight_type.items()
        if sum(s.runs for s in type_dict.values()) >= 5
    }

    # Find sweet spot: bucket with highest win_pct among those with >= 20 runs
    sweet_spot = None
    best_pct = 0.0
    for bkt, stats in by_weight.items():
        if stats.runs >= 20 and stats.win_pct > best_pct:
            best_pct = stats.win_pct
            sweet_spot = bkt

    return {
        "by_weight_bracket": weight_summary,
        "by_weight_and_type": weight_by_type,
        "sweet_spot_bracket": sweet_spot,
        "sweet_spot_win_pct": round(best_pct, 1) if sweet_spot else None,
    }


