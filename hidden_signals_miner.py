def main() -> int:
    parser = argparse.ArgumentParser(
        description="Mine hidden predictive signals from cached backtest data."
    )
    parser.add_argument(
        "--cache-dir",
        type=str,
        default=None,
        help="Override backtest cache directory (default: data/backtest_cache/)",
    )
    args = parser.parse_args()

    date_str = date.today().isoformat()
    print(f"hidden_signals_miner.py — {date_str}")

    cache_base = _cache_dir(args.cache_dir)
    print(f"Cache directory: {cache_base}")

    # --- Load data ---
    print("Loading racecards from cache...")
    all_races = load_all_racecards(cache_base)
    print(f"  Loaded {len(all_races)} races from cache.")

    print("Loading results lookup from cache...")
    result_lookup = load_results_lookup(cache_base)
    print(f"  Loaded {len(result_lookup)} horse results.")

    if not all_races:
        print(
            "\nWARNING: No cached racecards found at:\n"
            f"  {cache_base}/racecards/\n\n"
            "To populate: run  python historical_backtest.py --months 6\n"
            "on PythonAnywhere where API credentials are available.\n\n"
            "Proceeding with empty analysis — output will show structure only."
        )

    total_races = len(all_races)
    total_runners = sum(len(r.get("runners") or []) for r in all_races)

    # Count runners with result data
    total_runners_with_result = 0
    for race in all_races:
        for runner in (race.get("runners") or []):
            pos_int, _ = _get_position(runner, result_lookup)
            if pos_int != 99:
                total_runners_with_result += 1

    print(f"  Total runners: {total_runners}, with result data: {total_runners_with_result}")

    # --- Run analyses ---
    print("Analysing draw bias...")
    draw_r = analyse_draw(all_races, result_lookup)

    print("Analysing age patterns...")
    age_r = analyse_age(all_races, result_lookup)

    print("Analysing sex/gender patterns...")
    sex_r = analyse_sex(all_races, result_lookup)

    print("Analysing weight carried...")
    weight_r = analyse_weight(all_races, result_lookup)

    print("Analysing headgear signals...")
    headgear_r = analyse_headgear(all_races, result_lookup)

    print("Analysing wind surgery signal...")
    wind_r = analyse_wind_surgery(all_races, result_lookup)

    print("Analysing commentary / spotlight NLP...")
    commentary_r = analyse_commentary(all_races, result_lookup)

    print("Analysing trainer x jockey combinations...")
    trainer_jockey_r = analyse_trainer_jockey(all_races, result_lookup)

    print("Analysing quick return (flat vs jump split)...")
    quick_return_r = analyse_quick_return(all_races, result_lookup)

    # --- Generate recommendations ---
    print("Generating recommendations...")
    recommendations = generate_recommendations(
        draw_r, age_r, sex_r, weight_r, headgear_r, wind_r,
        commentary_r, trainer_jockey_r, quick_return_r,
        total_runners_with_result,
    )

    # --- Format report ---
    report_text = _format_report(
        date_str=date_str,
        total_races=total_races,
        total_runners=total_runners,
        total_runners_with_result=total_runners_with_result,
        draw_r=draw_r,
        age_r=age_r,
        sex_r=sex_r,
        weight_r=weight_r,
        headgear_r=headgear_r,
        wind_r=wind_r,
        commentary_r=commentary_r,
        trainer_jockey_r=trainer_jockey_r,
        quick_return_r=quick_return_r,
        recommendations=recommendations,
    )

    # --- Write outputs ---
    report_file = _report_path(f"hidden_signals_{date_str}.txt")
    try:
        with open(report_file, "w", encoding="utf-8") as fh:
            fh.write(report_text)
        print(f"\nReport written: {report_file}")
    except OSError as exc:
        print(f"ERROR: Failed to write report — {exc}", file=sys.stderr)
        return 1

    json_payload = {
        "generated_at": date_str,
        "data_summary": {
            "total_races": total_races,
            "total_runners": total_runners,
            "runners_with_result": total_runners_with_result,
        },
        "signals": {
            "1_draw_bias": draw_r,
            "2_age_patterns": age_r,
            "3_sex_patterns": sex_r,
            "4_weight_carried": weight_r,
            "5_headgear_first_time": headgear_r,
            "6_wind_surgery": wind_r,
            "7_commentary_nlp": commentary_r,
            "8_trainer_jockey_combos": trainer_jockey_r,
            "9_quick_return_split": quick_return_r,
        },
        "recommendations": recommendations,
    }

    json_file = _data_path(f"hidden_signals_{date_str}.json")
    try:
        with open(json_file, "w", encoding="utf-8") as fh:
            json.dump(json_payload, fh, indent=2, ensure_ascii=False)
        print(f"JSON written:   {json_file}")
    except (OSError, TypeError, ValueError) as exc:
        print(f"ERROR: Failed to write JSON — {exc}", file=sys.stderr)
        return 1

