"""
hidden_signals_miner.py — Mine hidden predictive signals from cached backtest data.

Analyses data/backtest_cache/racecards/*.json cross-referenced with
data/backtest_cache/results/*.json (and data/backtest_cache/race_results/*.json)
to find untapped predictors that the current nap_selector_v3 model ignores.

Signals investigated:
  1. Draw bias (flat only) — by distance group and course
  2. Age patterns — win rate by age, age × class
  3. Sex / gender patterns — win rate and variance
  4. Weight carried — win rate by weight bracket
  5. Headgear first-time — vs second-time vs no headgear
  6. Wind surgery signal — is the +3pt bonus calibrated correctly?
  7. Spotlight / commentary NLP — positive vs negative keyword win rates
  8. Trainer × jockey combination — "hot hands" combos
  9. Quick return (flat vs jumps split) — evidence for the pending fix

Outputs:
  reports/hidden_signals_{date_str}.txt
  data/hidden_signals_{date_str}.json

Usage:
  python hidden_signals_miner.py
  python hidden_signals_miner.py --cache-dir /custom/path

Exit codes:
  0 — report produced (even if no cached data — writes structure and notes)
  1 — fatal write error
"""

