def _is_flat(race: dict) -> bool:
    rt = _safe_str(race.get("type")).lower()
    return not any(x in rt for x in ("chase", "hurdle", "bumper", "nhf"))


def _is_jump(race: dict) -> bool:
    rt = _safe_str(race.get("type")).lower()
    return any(x in rt for x in ("chase", "hurdle", "bumper", "nhf"))


def _dist_group(f: float) -> str:
    if f <= 0:
        return "Unknown"
    if f < 7.0:
        return "Sprint (<7f)"
    if f < 10.5:
        return "Mile (7-10.5f)"
    if f < 14.0:
        return "Middle (10.5-14f)"
    return "Staying (14f+)"


def _dist_label_short(f: float) -> str:
    if f <= 0:
        return "?"
    if f < 7.0:
        return "sprint"
    if f < 10.5:
        return "mile"
    return "staying"


