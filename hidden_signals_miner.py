def analyse_wind_surgery(all_races: list[dict], result_lookup: dict) -> dict:
    """
    wind_surgery_run == 1 → first run after wind surgery
    Compare win rate vs baseline (no wind surgery).
    Current model gives +3pts for wind_surgery_run == 1.
    """
    first_run_stats = WinStats()
    established_stats = WinStats()   # wind_surgery_run >= 2
    no_surgery_stats = WinStats()
    surgery_unknown_stats = WinStats()

    # Also split by flat/jump
    first_run_flat = WinStats()
    first_run_jump = WinStats()

    for race in all_races:
        is_f = _is_flat(race)
        for runner in (race.get("runners") or []):
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            won = pos_int == 1
            placed = pos_int <= 3
            ws_run = _safe_int(runner.get("wind_surgery_run"), default=-1)

            if ws_run == 1:
                first_run_stats.record(won, placed, sp)
                if is_f:
                    first_run_flat.record(won, placed, sp)
                else:
                    first_run_jump.record(won, placed, sp)
            elif ws_run >= 2:
                established_stats.record(won, placed, sp)
            elif ws_run == 0:
                no_surgery_stats.record(won, placed, sp)
            else:
                surgery_unknown_stats.record(won, placed, sp)

    baseline_pct = None
    first_pct = None
    if no_surgery_stats.runs >= 20:
        baseline_pct = round(no_surgery_stats.win_pct, 2)
    if first_run_stats.runs >= 5:
        first_pct = round(first_run_stats.win_pct, 2)

    # Calibration: is +3pts justified?
    # +3pts on a 100pt scale ≈ 3% score boost. Meaningful if win rate is
    # notably above baseline.
    calibration_note = "insufficient data"
    if baseline_pct is not None and first_pct is not None:
        delta = first_pct - baseline_pct
        if delta >= 5.0:
            calibration_note = f"+3pts may be UNDER-valued (actual edge +{delta:.1f}%)"
        elif delta >= 2.0:
            calibration_note = f"+3pts appropriate (actual edge +{delta:.1f}%)"
        elif delta >= 0:
            calibration_note = f"+3pts generous (actual edge only +{delta:.1f}%)"
        else:
            calibration_note = f"+3pts NOT JUSTIFIED — wind surgery horses win LESS often ({delta:.1f}%)"

    return {
        "first_run_after_surgery": first_run_stats.to_dict(),
        "first_run_flat": first_run_flat.to_dict(),
        "first_run_jump": first_run_jump.to_dict(),
        "established_surgery": established_stats.to_dict(),
        "no_surgery_baseline": no_surgery_stats.to_dict(),
        "baseline_win_pct": baseline_pct,
        "first_run_win_pct": first_pct,
        "calibration_note": calibration_note,
    }


