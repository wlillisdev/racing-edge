def analyse_trainer_jockey(all_races: list[dict], result_lookup: dict) -> dict:
    combo_stats: dict[str, WinStats] = defaultdict(WinStats)
    trainer_stats: dict[str, WinStats] = defaultdict(WinStats)
    jockey_stats: dict[str, WinStats] = defaultdict(WinStats)

    for race in all_races:
        for runner in (race.get("runners") or []):
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            won = pos_int == 1
            placed = pos_int <= 3
            trainer = _safe_str(runner.get("trainer"))
            jockey = _safe_str(runner.get("jockey"))

            if trainer:
                trainer_stats[trainer].record(won, placed, sp)
            if jockey:
                jockey_stats[jockey].record(won, placed, sp)
            if trainer and jockey:
                combo_key = f"{trainer} / {jockey}"
                combo_stats[combo_key].record(won, placed, sp)

    # Filter combos with >= 5 runs
    qualified_combos = [
        (combo, stats)
        for combo, stats in combo_stats.items()
        if stats.runs >= 5
    ]
    qualified_combos.sort(key=lambda x: x[1].win_pct, reverse=True)

    top_combos: list[dict] = []
    for combo, stats in qualified_combos[:20]:
        trainer, jockey = combo.split(" / ", 1) if " / " in combo else (combo, "")
        # Marginal edge = combo win% - (trainer_win% + jockey_win%) / 2
        t_pct = trainer_stats[trainer].win_pct if trainer and trainer_stats[trainer].runs >= 5 else None
        j_pct = jockey_stats[jockey].win_pct if jockey and jockey_stats[jockey].runs >= 5 else None
        if t_pct is not None and j_pct is not None:
            expected = (t_pct + j_pct) / 2
            edge = round(stats.win_pct - expected, 1)
        else:
            edge = None
        top_combos.append({
            "combo": combo,
            "runs": stats.runs,
            "wins": stats.wins,
            "win_pct": round(stats.win_pct, 1),
            "place_pct": round(stats.place_pct, 1),
            "trainer_solo_win_pct": round(t_pct, 1) if t_pct else None,
            "jockey_solo_win_pct": round(j_pct, 1) if j_pct else None,
            "combo_edge_over_solo_avg": edge,
        })

    # Top 10 trainers and jockeys by win %
    top_trainers = sorted(
        [(t, s) for t, s in trainer_stats.items() if s.runs >= 10],
        key=lambda x: x[1].win_pct, reverse=True
    )[:10]
    top_jockeys = sorted(
        [(j, s) for j, s in jockey_stats.items() if s.runs >= 10],
        key=lambda x: x[1].win_pct, reverse=True
    )[:10]

    return {
        "total_trainer_jockey_combos_with_5plus_runs": len(qualified_combos),
        "top_10_hot_hands_combos": top_combos[:10],
        "top_10_trainers_by_win_pct": [
            {"trainer": t, **s.to_dict()} for t, s in top_trainers
        ],
        "top_10_jockeys_by_win_pct": [
            {"jockey": j, **s.to_dict()} for j, s in top_jockeys
        ],
        "model_gap_note": (
            "Current model accounts for trainer 14-day form (0-15pts) "
            "but NOT for jockey or trainer×jockey combination. "
            "Adding combo bonus of +2 to +5pts for top combos could improve selection."
        ),
    }


