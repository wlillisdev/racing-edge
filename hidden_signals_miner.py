def _load_json(path: Path) -> Optional[dict]:
    if not path.exists():
        return None
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def load_all_racecards(cache_base: Path) -> list[dict]:
    """
    Load all racecard files from cache_base/racecards/*.json.
    Each file has structure: {"races": [ {race_dict}, ... ]}
    Returns a flat list of race dicts (each with a "runners" list).
    """
    rc_dir = cache_base / "racecards"
    if not rc_dir.exists():
        return []

    all_races: list[dict] = []
    for f in sorted(rc_dir.glob("*.json")):
        data = _load_json(f)
        if not data:
            continue
        races = data.get("races") or []
        for race in races:
            race["_source_file"] = f.stem   # date string for debug
            all_races.append(race)
    return all_races


def load_results_lookup(cache_base: Path) -> dict[str, dict]:
    """
    Build a horse_id → {position, sp_dec} lookup from all cached race results.
    Checks two cache locations:
      - cache_base/race_results/<race_id>.json  {"runners": {horse_id: {pos, sp}}}
      - cache_base/results/<date>.json          (legacy daily format)
    """
    lookup: dict[str, dict] = {}

    # Per-race results cache (preferred — generated by historical_backtest.py)
    rr_dir = cache_base / "race_results"
    if rr_dir.exists():
        for f in sorted(rr_dir.glob("*.json")):
            data = _load_json(f)
            if not data:
                continue
            runners = data.get("runners") or {}
            for hid, rdata in runners.items():
                if hid and hid not in lookup:
                    lookup[hid] = rdata

    # Legacy daily results cache (fallback)
    res_dir = cache_base / "results"
    if res_dir.exists():
        for f in sorted(res_dir.glob("*.json")):
            data = _load_json(f)
            if not data:
                continue
            # Support multiple possible shapes
            runners_raw = (
                data.get("runners")
                or data.get("results")
                or []
            )
            if isinstance(runners_raw, list):
                for r in runners_raw:
                    hid = _safe_str(r.get("horse_id"))
                    pos = _safe_str(r.get("position") or r.get("finish_position"))
                    sp = _safe_float(r.get("sp_dec") or r.get("bsp") or r.get("sp"))
                    if hid and hid not in lookup:
                        lookup[hid] = {"position": pos, "sp_dec": sp}
            elif isinstance(runners_raw, dict):
                for hid, rdata in runners_raw.items():
                    if hid and hid not in lookup:
                        lookup[hid] = rdata

    return lookup


