# Positive signals — suggest trainer confidence, horse in good form
_POSITIVE_KEYWORDS = [
    "improves", "progressive", "well held", "going well",
    "fit", "interesting", "danger", "danger here", "chance",
    "could go well", "capable", "promising", "exciting",
    "big run", "bold bid", "right in contention",
    "fancied", "market confident", "ready",
]

# Negative signals — suggest excuses or decline
_NEGATIVE_KEYWORDS = [
    "disappointing", "beaten favourite", "struggle", "needs",
    "below par", "below form", "out of form", "not beaten far",
    "hard to fancy", "hard to see", "looks held", "beaten easily",
    "unproven", "worried", "poor effort", "well beaten",
    "not for us", "avoid", "too big an ask", "tough task",
]

# Strong positive phrases from stable tours / quotes
_STRONG_POSITIVE = [
    "should win", "win this", "expected to win", "strong fancy",
    "love this horse", "very well", "highly tried",
    "excited about", "best performance",
]

# Strong negative phrases
_STRONG_NEGATIVE = [
    "not entered by mistake", "needs a break", "not right",
    "gallop a concern", "lame", "injury",
]


def _score_text(text: str) -> tuple[int, list[str]]:
    """
    Return (sentiment_score, matched_keywords).
    Positive match = +1, negative match = -1, strong +/- = ±2.
    """
    if not text:
        return 0, []
    t = text.lower()
    score = 0
    matched: list[str] = []
    for kw in _STRONG_POSITIVE:
        if kw in t:
            score += 2
            matched.append(f"+2:{kw}")
    for kw in _STRONG_NEGATIVE:
        if kw in t:
            score -= 2
            matched.append(f"-2:{kw}")
    for kw in _POSITIVE_KEYWORDS:
        if kw in t and f"+2:{kw}" not in matched:
            score += 1
            matched.append(f"+1:{kw}")
    for kw in _NEGATIVE_KEYWORDS:
        if kw in t and f"-2:{kw}" not in matched:
            score -= 1
            matched.append(f"-1:{kw}")
    return score, matched


def analyse_commentary(all_races: list[dict], result_lookup: dict) -> dict:
    # sentiment_bucket ("strong_pos", "mild_pos", "neutral", "mild_neg", "strong_neg")
    sentiment_stats: dict[str, WinStats] = defaultdict(WinStats)
    # keyword -> WinStats (for individual keyword alpha)
    keyword_stats: dict[str, WinStats] = defaultdict(WinStats)

    field_count = 0
    any_text_count = 0

    for race in all_races:
        for runner in (race.get("runners") or []):
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue
            field_count += 1
            won = pos_int == 1
            placed = pos_int <= 3

            # Combine all commentary fields
            text_parts = [
                _safe_str(runner.get("spotlight")),
                _safe_str(runner.get("comment")),
                _safe_str(runner.get("quotes")),
                _safe_str(runner.get("stable_tour")),
            ]
            combined_text = " ".join(p for p in text_parts if p)

            if not combined_text:
                sentiment_stats["no_commentary"].record(won, placed, sp)
                continue

            any_text_count += 1
            sent_score, matched_kws = _score_text(combined_text)

            if sent_score >= 3:
                bucket = "strong_positive"
            elif sent_score >= 1:
                bucket = "mild_positive"
            elif sent_score <= -3:
                bucket = "strong_negative"
            elif sent_score <= -1:
                bucket = "mild_negative"
            else:
                bucket = "neutral"

            sentiment_stats[bucket].record(won, placed, sp)

            # Per-keyword stats
            for kw_label in matched_kws:
                keyword_stats[kw_label].record(won, placed, sp)

    # Find high-alpha keywords (win rate vs baseline, min 10 occurrences)
    baseline_pct = None
    if sentiment_stats["neutral"].runs >= 10:
        baseline_pct = sentiment_stats["neutral"].win_pct

    high_alpha_keywords: list[dict] = []
    for kw, stats in keyword_stats.items():
        if stats.runs >= 10 and baseline_pct is not None:
            delta = stats.win_pct - baseline_pct
            high_alpha_keywords.append({
                "keyword": kw,
                "runs": stats.runs,
                "wins": stats.wins,
                "win_pct": round(stats.win_pct, 1),
                "vs_baseline": round(delta, 1),
            })
    high_alpha_keywords.sort(key=lambda x: x["vs_baseline"], reverse=True)

    return {
        "runners_with_result": field_count,
        "runners_with_commentary": any_text_count,
        "commentary_coverage_pct": round(any_text_count / field_count * 100, 1) if field_count else 0.0,
        "by_sentiment": {
            bucket: stats.to_dict()
            for bucket, stats in sentiment_stats.items()
            if stats.runs >= 3
        },
        "high_alpha_keywords": high_alpha_keywords[:20],
        "baseline_neutral_win_pct": round(baseline_pct, 2) if baseline_pct else None,
    }


