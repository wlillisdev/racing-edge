class WinStats:
    """Accumulate wins / runs / variance for a categorical group."""

    __slots__ = ("runs", "wins", "places", "sp_sum", "sp_sq_sum")

    def __init__(self):
        self.runs = 0
        self.wins = 0
        self.places = 0    # top-3 finishes
        self.sp_sum = 0.0
        self.sp_sq_sum = 0.0

    def record(self, won: bool, placed: bool, sp: float = 0.0):
        self.runs += 1
        if won:
            self.wins += 1
        if placed:
            self.places += 1
        if sp > 1.0:
            self.sp_sum += sp
            self.sp_sq_sum += sp * sp

    @property
    def win_pct(self) -> float:
        return self.wins / self.runs * 100.0 if self.runs else 0.0

    @property
    def place_pct(self) -> float:
        return self.places / self.runs * 100.0 if self.runs else 0.0

    def to_dict(self) -> dict:
        return {
            "runs": self.runs,
            "wins": self.wins,
            "places": self.places,
            "win_pct": round(self.win_pct, 2),
            "place_pct": round(self.place_pct, 2),
        }


def _get_position(runner: dict, result_lookup: dict) -> tuple[int, float]:
    """Return (position_int, sp_dec) for a runner. 99 means unknown/unplaced."""
    hid = _safe_str(runner.get("horse_id"))
    # Check racecard-embedded position first (some API configs embed it)
    pos_raw = _safe_str(runner.get("position"))
    sp_raw = _safe_float(runner.get("sp_dec"))
    if not pos_raw and hid and hid in result_lookup:
        rd = result_lookup[hid]
        pos_raw = _safe_str(rd.get("position"))
        sp_raw = _safe_float(rd.get("sp_dec"))
    try:
        pos_int = int(pos_raw)
    except (ValueError, TypeError):
        pos_int = 99
    return pos_int, sp_raw


