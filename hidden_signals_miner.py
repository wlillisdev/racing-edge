def _format_report(
    date_str: str,
    total_races: int,
    total_runners: int,
    total_runners_with_result: int,
    draw_r: dict,
    age_r: dict,
    sex_r: dict,
    weight_r: dict,
    headgear_r: dict,
    wind_r: dict,
    commentary_r: dict,
    trainer_jockey_r: dict,
    quick_return_r: dict,
    recommendations: list[dict],
) -> str:
    SEP = "=" * 72
    sep = "-" * 72
    lines = [
        SEP,
        "  RACING EDGE — HIDDEN SIGNALS MINING REPORT",
        f"  Generated: {date_str}",
        f"  Data: {total_races} races | {total_runners} runners | {total_runners_with_result} with result data",
        SEP,
    ]

    def _section(title: str):
        lines.append("")
        lines.append(f"{'█' * 2} {title}")
        lines.append(sep)

    # ---- Draw ----
    _section("SIGNAL 1: DRAW BIAS (FLAT RACING)")
    if draw_r.get("runners_analysed", 0) == 0:
        lines.append("  No flat draw data in cache. Run on PythonAnywhere to populate.")
    else:
        lines.append(f"  Runners analysed: {draw_r.get('runners_analysed')} across {draw_r.get('races_with_flat_draw_data')} races")
        for dist, thirds in (draw_r.get("by_distance_group") or {}).items():
            low = thirds.get("low") or {}
            mid = thirds.get("mid") or {}
            high = thirds.get("high") or {}
            lines.append(
                f"  {dist:<22} "
                f"Low draw: {low.get('win_pct', 0):>5.1f}% ({low.get('runs', 0):>4} runs)  "
                f"Mid: {mid.get('win_pct', 0):>5.1f}% ({mid.get('runs', 0):>4})  "
                f"High: {high.get('win_pct', 0):>5.1f}% ({high.get('runs', 0):>4})"
            )
        lines.append("")
        lines.append("  Top Biased Courses:")
        if draw_r.get("top_5_biased_courses"):
            for c in draw_r["top_5_biased_courses"]:
                lines.append(
                    f"    {c['course']:<20} {c['direction']:<22} bias={c['bias_magnitude_pct']:>4.1f}%  "
                    f"low={c.get('low_win_pct', 0):.1f}% mid={c.get('mid_win_pct', 0):.1f}% high={c.get('high_win_pct', 0):.1f}%"
                )
        else:
            lines.append("    Insufficient data (need 20+ runs per course)")

    # ---- Age ----
    _section("SIGNAL 2: AGE PATTERNS")
    age_by = age_r.get("by_age") or {}
    if age_by:
        lines.append(f"  {'Age':<10} {'Runs':>6} {'Wins':>5} {'Win%':>6} {'Place%':>7} {'PosStdDev':>10}")
        for bucket in ["2yo", "3yo", "4yo", "5yo", "6yo", "7yo+"]:
            if bucket in age_by:
                d = age_by[bucket]
                std = d.get("position_std_dev")
                std_s = f"{std:.2f}" if std else "  N/A"
                lines.append(
                    f"  {bucket:<10} {d.get('runs', 0):>6} {d.get('wins', 0):>5} "
                    f"{d.get('win_pct', 0):>5.1f}% {d.get('place_pct', 0):>6.1f}% {std_s:>10}"
                )
    else:
        lines.append("  No age data available.")

    # ---- Sex ----
    _section("SIGNAL 3: SEX / GENDER PATTERNS")
    sex_by = sex_r.get("by_sex") or {}
    if sex_by:
        lines.append(f"  {'Sex':<20} {'Runs':>6} {'Wins':>5} {'Win%':>6} {'Place%':>7} {'PosStdDev':>10}")
        for bkt, d in sorted(sex_by.items(), key=lambda x: -x[1].get("win_pct", 0)):
            if d.get("runs", 0) >= 5:
                std = d.get("position_std_dev")
                std_s = f"{std:.2f}" if std else "  N/A"
                lines.append(
                    f"  {bkt:<20} {d.get('runs', 0):>6} {d.get('wins', 0):>5} "
                    f"{d.get('win_pct', 0):>5.1f}% {d.get('place_pct', 0):>6.1f}% {std_s:>10}"
                )
    else:
        lines.append("  No sex data available.")

    # ---- Weight ----
    _section("SIGNAL 4: WEIGHT CARRIED")
    wt_by = weight_r.get("by_weight_bracket") or {}
    if wt_by:
        sweet = weight_r.get("sweet_spot_bracket")
        lines.append(f"  {'Weight Bracket':<25} {'Runs':>6} {'Wins':>5} {'Win%':>6}")
        ordered_buckets = [
            "<8-7 (featherweight)",
            "8-7 to 8-13",
            "9-0 to 9-6",
            "9-7 to 9-13",
            "10-0+ (topweight)",
            "Unknown",
        ]
        for bkt in ordered_buckets:
            d = wt_by.get(bkt)
            if not d or d.get("runs", 0) < 5:
                continue
            marker = " ***SWEET SPOT***" if bkt == sweet else ""
            lines.append(
                f"  {bkt:<25} {d.get('runs', 0):>6} {d.get('wins', 0):>5} "
                f"{d.get('win_pct', 0):>5.1f}%{marker}"
            )
        for bkt, d in wt_by.items():
            if bkt not in ordered_buckets and d.get("runs", 0) >= 5:
                marker = " ***SWEET SPOT***" if bkt == sweet else ""
                lines.append(
                    f"  {bkt:<25} {d.get('runs', 0):>6} {d.get('wins', 0):>5} "
                    f"{d.get('win_pct', 0):>5.1f}%{marker}"
                )
    else:
        lines.append("  No weight data available.")

    # ---- Headgear ----
    _section("SIGNAL 5: HEADGEAR FIRST-TIME ANALYSIS")
    hg_by = headgear_r.get("by_headgear_status") or {}
    baseline_hg = headgear_r.get("baseline_no_headgear_win_pct")
    delta_hg = headgear_r.get("first_time_vs_baseline_delta")
    if hg_by:
        lines.append(f"  {'Status':<20} {'Runs':>6} {'Wins':>5} {'Win%':>6}")
        for status in ["no_headgear", "first_time", "second_time", "established"]:
            d = hg_by.get(status)
            if d and d.get("runs", 0) >= 3:
                lines.append(
                    f"  {status:<20} {d.get('runs', 0):>6} {d.get('wins', 0):>5} {d.get('win_pct', 0):>5.1f}%"
                )
        if baseline_hg is not None:
            lines.append(f"  Baseline (no headgear): {baseline_hg}%")
        if delta_hg is not None:
            delta_arrow = "^" if delta_hg > 0 else "v"
            lines.append(f"  First-time headgear vs baseline: {delta_hg:+.1f}% ({delta_arrow})")

        # By headgear type
        hg_types = headgear_r.get("first_time_by_headgear_type") or {}
        if hg_types:
            lines.append("  By headgear type (first time only):")
            for hg_type, d in sorted(hg_types.items(), key=lambda x: -x[1].get("win_pct", 0)):
                if d.get("runs", 0) >= 3:
                    lines.append(
                        f"    {hg_type:<20} {d.get('runs', 0):>4} runs  {d.get('win_pct', 0):>5.1f}% win"
                    )
    else:
        lines.append("  No headgear data available.")

    # ---- Wind surgery ----
    _section("SIGNAL 6: WIND SURGERY (current model: +3pts)")
    wf_first = wind_r.get("first_run_win_pct")
    wf_base = wind_r.get("baseline_win_pct")
    wf_note = wind_r.get("calibration_note", "insufficient data")
    wf_runs = wind_r.get("first_run_after_surgery", {}).get("runs", 0)
    lines.append(f"  First run after wind surgery: {wf_runs} cases")
    if wf_first is not None:
        lines.append(f"  Win rate:  {wf_first}%  (first run after surgery)")
    if wf_base is not None:
        lines.append(f"  Baseline:  {wf_base}%  (no surgery horses)")
    lines.append(f"  Calibration: {wf_note}")

    # ---- Commentary ----
    _section("SIGNAL 7: SPOTLIGHT / COMMENTARY NLP")
    coverage = commentary_r.get("commentary_coverage_pct", 0)
    lines.append(f"  Commentary coverage: {coverage}%")
    sent_by = commentary_r.get("by_sentiment") or {}
    baseline_sent = commentary_r.get("baseline_neutral_win_pct")
    if baseline_sent:
        lines.append(f"  Neutral commentary baseline: {baseline_sent}%")
    lines.append(f"  {'Sentiment':<20} {'Runs':>6} {'Wins':>5} {'Win%':>6}")
    for bucket in ["strong_positive", "mild_positive", "neutral", "mild_negative", "strong_negative", "no_commentary"]:
        d = sent_by.get(bucket)
        if d and d.get("runs", 0) >= 3:
            lines.append(
                f"  {bucket:<20} {d.get('runs', 0):>6} {d.get('wins', 0):>5} {d.get('win_pct', 0):>5.1f}%"
            )
    high_alpha = commentary_r.get("high_alpha_keywords") or []
    if high_alpha:
        lines.append("  High-alpha keywords (10+ occurrences):")
        for kw in high_alpha[:10]:
            lines.append(
                f"    {kw['keyword']:<30} {kw['runs']:>4} runs  win={kw['win_pct']:.1f}%  vs_baseline={kw['vs_baseline']:+.1f}%"
            )

    # ---- Trainer × Jockey ----
    _section("SIGNAL 8: TRAINER x JOCKEY HOT HANDS")
    n_combos = trainer_jockey_r.get("total_trainer_jockey_combos_with_5plus_runs", 0)
    lines.append(f"  Combos with 5+ runs: {n_combos}")
    top_combos = trainer_jockey_r.get("top_10_hot_hands_combos") or []
    if top_combos:
        lines.append(f"  {'Combo':<45} {'Runs':>5} {'Win%':>6} {'Edge':>6}")
        for c in top_combos[:10]:
            edge_s = f"{c.get('combo_edge_over_solo_avg', 0):+.1f}%" if c.get("combo_edge_over_solo_avg") is not None else "  N/A"
            lines.append(
                f"  {c.get('combo', '?'):<45} {c.get('runs', 0):>5} {c.get('win_pct', 0):>5.1f}% {edge_s:>6}"
            )
    lines.append(f"  Note: {trainer_jockey_r.get('model_gap_note', '')}")

    # ---- Quick return ----
    _section("SIGNAL 9: QUICK RETURN — FLAT vs JUMPS (PENDING FIX)")
    qr_comp = quick_return_r.get("quick_return_comparison") or {}
    qr_assess = quick_return_r.get("assessment", "insufficient data")
    lines.append(f"  Assessment: {qr_assess}")
    if qr_comp:
        for key, val in qr_comp.items():
            lines.append(f"    {key}: {val}%")
    qr_by_type = quick_return_r.get("by_race_type_and_days_since_last_run") or {}
    for type_tag in ("flat", "jump"):
        type_data = qr_by_type.get(type_tag) or {}
        if type_data:
            lines.append(f"  {type_tag.upper()} return profile:")
            for bkt in ["<7_days", "7-13_days", "14-27_days", "28-44_days", "45-69_days", "70+_days"]:
                d = type_data.get(bkt)
                if d and d.get("runs", 0) >= 5:
                    lines.append(
                        f"    {bkt:<15} {d.get('runs', 0):>5} runs  win={d.get('win_pct', 0):>5.1f}%  place={d.get('place_pct', 0):>5.1f}%"
                    )

    # ---- Top 5 recommendations ----
    _section("TOP RECOMMENDATIONS (RANKED BY ESTIMATED IMPACT)")
    if not recommendations:
        lines.append("  No recommendations (no data — run on PythonAnywhere to populate).")
    else:
        for rec in recommendations[:5]:
            lines.append(f"  #{rec['rank']}  [{rec['significance']}]  {rec['signal']}")
            lines.append(f"     Evidence:       {rec.get('evidence', '')}")
            lines.append(f"     Recommendation: {rec.get('recommendation', '')}")
            lines.append(f"     Est. Impact:    {rec.get('estimated_impact', '')}")
            lines.append("")

    lines.append(SEP)
    lines.append("  NOTE: This report is based on cached backtest data.")
    lines.append("  If cache is empty, all 'PENDING_DATA' signals need PythonAnywhere run.")
    lines.append("  Recommended: python historical_backtest.py --months 6  (populate cache)")
    lines.append("  Then:        python hidden_signals_miner.py  (re-run analysis)")
    lines.append(SEP)

    return "\n".join(lines)


