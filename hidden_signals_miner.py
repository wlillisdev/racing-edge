# ---------------------------------------------------------------------------

def analyse_draw(all_races: list[dict], result_lookup: dict) -> dict:
    """
    Flat races only.
    For each runner: record draw, normalised draw, distance group, course.
    Compute win rates for low/mid/high draw thirds by distance group.
    Also compute per-course draw bias (courses with 10+ flat races).
    """
    # dist_group -> draw_third ("low"/"mid"/"high") -> WinStats
    by_dist_draw: dict[str, dict[str, WinStats]] = defaultdict(
        lambda: {"low": WinStats(), "mid": WinStats(), "high": WinStats()}
    )
    # course -> draw_third -> WinStats
    by_course_draw: dict[str, dict[str, WinStats]] = defaultdict(
        lambda: {"low": WinStats(), "mid": WinStats(), "high": WinStats()}
    )
    # raw draw number -> WinStats (sprint flat only, pooled)
    draw_number_sprint: dict[int, WinStats] = defaultdict(WinStats)

    races_processed = 0
    runners_processed = 0
    races_with_draw = 0

    for race in all_races:
        if not _is_flat(race):
            continue
        dist_f = _safe_float(race.get("distance_f"))
        course = _safe_str(race.get("course"))
        runners = race.get("runners") or []
        field_size = max(_safe_int(race.get("field_size"), default=len(runners)), len(runners))
        if field_size < 3:
            continue

        # Check whether draw data is present at all
        draws = [_safe_int(r.get("draw"), default=-1) for r in runners]
        valid_draws = [d for d in draws if d > 0]
        if not valid_draws:
            continue

        races_with_draw += 1
        races_processed += 1
        dist_grp = _dist_group(dist_f)

        for runner in runners:
            draw_val = _safe_int(runner.get("draw"), default=-1)
            if draw_val <= 0:
                continue
            pos_int, sp = _get_position(runner, result_lookup)
            if pos_int == 99:
                continue   # no result — skip

            won = pos_int == 1
            placed = pos_int <= 3

            # Normalised draw: 0.0 (lowest) to 1.0 (highest)
            norm_draw = (draw_val - 1) / max(field_size - 1, 1)
            if norm_draw < 0.333:
                draw_third = "low"
            elif norm_draw < 0.667:
                draw_third = "mid"
            else:
                draw_third = "high"

            by_dist_draw[dist_grp][draw_third].record(won, placed, sp)
            by_course_draw[course][draw_third].record(won, placed, sp)
            runners_processed += 1

            if dist_f < 7.0:
                draw_number_sprint[draw_val].record(won, placed, sp)

    # --- Compute bias scores per course ---
    # Bias = |low_win_pct - high_win_pct|, only where each cell has >= 5 runs
    course_bias: list[tuple[str, float, str, dict]] = []
    for course, thirds in by_course_draw.items():
        low_s = thirds["low"]
        high_s = thirds["high"]
        total_runs = sum(t.runs for t in thirds.values())
        if total_runs < 20:
            continue
        if low_s.runs < 5 or high_s.runs < 5:
            continue
        bias = low_s.win_pct - high_s.win_pct
        direction = "LOW_DRAW_FAVOURED" if bias > 0 else "HIGH_DRAW_FAVOURED"
        course_bias.append((
            course,
            abs(bias),
            direction,
            {
                "low_runs": low_s.runs, "low_win_pct": round(low_s.win_pct, 1),
                "mid_runs": thirds["mid"].runs, "mid_win_pct": round(thirds["mid"].win_pct, 1),
                "high_runs": high_s.runs, "high_win_pct": round(high_s.win_pct, 1),
                "bias_pct": round(bias, 1),
            }
        ))
    course_bias.sort(key=lambda x: x[1], reverse=True)
    top_courses = course_bias[:5]

    # --- Build distance summary ---
    dist_summary: dict[str, dict] = {}
    for dist_grp, thirds in by_dist_draw.items():
        dist_summary[dist_grp] = {
            third: thirds[third].to_dict() for third in ("low", "mid", "high")
        }

    # --- Sprint stall analysis (top 10 stalls by win %) ---
    sprint_stalls = []
    for stall, stats in sorted(draw_number_sprint.items()):
        if stats.runs >= 5:
            sprint_stalls.append({
                "stall": stall,
                "runs": stats.runs,
                "wins": stats.wins,
                "win_pct": round(stats.win_pct, 1),
            })
    sprint_stalls.sort(key=lambda x: x["win_pct"], reverse=True)

    return {
        "races_with_flat_draw_data": races_with_draw,
        "runners_analysed": runners_processed,
        "by_distance_group": dist_summary,
        "top_5_biased_courses": [
            {
                "course": c,
                "bias_magnitude_pct": round(b, 1),
                "direction": d,
                **data,
            }
            for c, b, d, data in top_courses
        ],
        "sprint_stall_win_rates": sprint_stalls[:15],
    }


